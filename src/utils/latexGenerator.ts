import { PatentSpecification } from '../types';

export function generatePatentLatex(spec: PatentSpecification): string {
  const jurisdiction = spec.metadata?.jurisdiction || 'IPO';
  const isIPO = jurisdiction === 'IPO';
  const isUSPTO = jurisdiction === 'USPTO';
  const isPCT = jurisdiction === 'PCT';

  const titleEscaped = escapeLatex(spec.title || 'UNTITLED INVENTION');
  const inventorsList = spec.metadata?.inventors?.map(i => escapeLatex(i.name) + (i.affiliation ? ` (${escapeLatex(i.affiliation)})` : '')).join(', ') || 'Inventors not specified';
  const applicantName = escapeLatex(spec.metadata?.applicant?.name || 'Applicant Institution');

  let latex = `% ==============================================================================
% PATENT SPECIFICATION - OFFICIAL PATENT OFFICE FORMAT
% Generated by PatentSpec Formatter for Academic & Research Institutions
% Jurisdiction: ${jurisdiction} | Specification Type: ${spec.metadata?.filingType?.toUpperCase() || 'COMPLETE'}
% ==============================================================================

\\documentclass[12pt,a4paper]{article}

% --- Essential Patent Typography Packages ---
\\usepackage[top=25.4mm,bottom=25.4mm,left=25.4mm,right=25.4mm]{geometry} % Standard 1-inch margins
\\usepackage{setspace}
\\onehalfspacing % Patent specifications require 1.5 line spacing
\\usepackage{lineno} % Line numbering required by many patent examiners
\\usepackage{fancyhdr}
\\usepackage{amsmath,amssymb}
\\usepackage{enumitem}
\\usepackage{microtype}
\\usepackage[hidelinks]{hyperref}

% --- Header & Footer Configuration ---
\\pagestyle{fancy}
\\fancyhf{}
\\rhead{\\small ${jurisdiction} Specification - ${spec.metadata?.filingType === 'provisional' ? 'Provisional' : 'Complete'}}
\\lhead{\\small \\truncate{0.45\\textwidth}{${titleEscaped}}}
\\cfoot{\\thepage}
\\renewcommand{\\headrulewidth}{0.4pt}
\\renewcommand{\\footrulewidth}{0.4pt}

% Line numbers styling
\\renewcommand\\linenumberfont{\\normalfont\\tiny\\sffamily\\color{gray}}
\\setlength\\linenumbersep{12pt}

\\begin{document}
\\linenumbers % Turn on line numbers for examination review
`;

  if (isIPO) {
    // Standard Indian Patent Office Form 2 Header
    latex += `
% ------------------------------------------------------------------------------
% FORM 2 (THE PATENTS ACT, 1970 - 39 of 1970) & THE PATENTS RULES, 2003
% COMPLETE SPECIFICATION (See Section 10 and Rule 13)
% ------------------------------------------------------------------------------
\\begin{center}
    {\\bfseries\\large FORM 2}\\\\
    {\\bfseries THE PATENTS ACT, 1970}\\\\
    (39 of 1970)\\\\&\\\\
    {\\bfseries THE PATENTS RULES, 2003}\\\\
    \\vspace{0.4cm}
    {\\bfseries\\Large COMPLETE SPECIFICATION}\\\\
    {\\small (See section 10 and rule 13)}\\\\
\\end{center}

\\vspace{0.6cm}
\\noindent
{\\bfseries 1. TITLE OF THE INVENTION:}\\\\
\\vspace{0.2cm}
{\\large\\bfseries ${titleEscaped}}

\\vspace{0.6cm}
\\noindent
{\\bfseries 2. APPLICANT(S):}\\\\
\\noindent
\\textbf{Name:} ${applicantName}\\\\
\\textbf{Nationality:} Indian\\\\
\\textbf{Address:} As on Record\\\\

\\vspace{0.4cm}
\\noindent
{\\bfseries 3. INVENTOR(S):}\\\\
\\noindent
${inventorsList}\\\\

\\vspace{0.6cm}
\\noindent
{\\bfseries 4. PREAMBLE TO THE DESCRIPTION:}\\\\
\\noindent
\\textit{${escapeLatex(spec.preamble || 'The following specification particularly describes the invention and the manner in which it is to be performed.')}}

\\vspace{0.6cm}
\\hrule
\\vspace{0.6cm}
`;
  } else if (isUSPTO) {
    latex += `
% ------------------------------------------------------------------------------
% USPTO SPECIFICATION (37 CFR 1.77 Standard Format)
% ------------------------------------------------------------------------------
\\begin{center}
    {\\Large\\bfseries ${titleEscaped}}\\\\
    \\vspace{0.4cm}
    {\\small INVENTORS: ${inventorsList}}\\\\
    {\\small APPLICANT: ${applicantName}}\\\\
\\end{center}

\\vspace{0.6cm}
`;
  } else {
    latex += `
% ------------------------------------------------------------------------------
% PCT / INTERNATIONAL PATENT APPLICATION SPECIFICATION
% Standard WIPO ST.10/C Format
% ------------------------------------------------------------------------------
\\begin{center}
    {\\Large\\bfseries ${titleEscaped}}\\\\
    \\vspace{0.3cm}
    {\\small ${jurisdiction} PATENT SPECIFICATION}\\\\
\\end{center}

\\vspace{0.5cm}
`;
  }

  // Field of Invention
  latex += `
% --- FIELD OF THE INVENTION ---
\\section*{${isIPO ? 'FIELD OF THE INVENTION' : 'FIELD OF THE INVENTION'}}
\\noindent
${escapeLatex(spec.fieldOfInvention || 'The present invention relates generally to technical systems and methods, and more specifically to the embodiments described herein.')}

`;

  // Background of the Invention
  latex += `
% --- BACKGROUND OF THE INVENTION ---
\\section*{${isIPO ? 'BACKGROUND OF THE INVENTION AND PRIOR ART' : 'BACKGROUND OF THE INVENTION'}}
\\noindent
${escapeLatex(spec.backgroundOfInvention || 'Prior art systems suffer from several limitations in performance, reliability, and computational efficiency.')}

`;

  // Prior Art Limitations
  if (spec.priorArtLimitations && spec.priorArtLimitations.length > 0) {
    latex += `
\\vspace{0.2cm}
\\noindent
Deficiencies in the existing state of the art include:
\\begin{itemize}[leftmargin=*,noitemsep]
${spec.priorArtLimitations.map(item => `  \\item ${escapeLatex(item)}`).join('\n')}
\\end{itemize}
`;
  }

  // Objects of Invention (Especially favored in IPO Form 2)
  if (spec.objectsOfInvention && spec.objectsOfInvention.length > 0) {
    latex += `
% --- OBJECTS OF THE INVENTION ---
\\section*{OBJECTS OF THE INVENTION}
\\noindent
The primary and secondary objectives of the present invention are set forth below:
\\begin{itemize}[leftmargin=*,noitemsep]
${spec.objectsOfInvention.map(obj => `  \\item ${escapeLatex(obj)}`).join('\n')}
\\end{itemize}
`;
  }

  // Summary of Invention
  latex += `
% --- SUMMARY OF THE INVENTION ---
\\section*{SUMMARY OF THE INVENTION}
\\noindent
${escapeLatex(spec.summaryOfInvention || 'In accordance with an embodiment of the present disclosure, an apparatus and method are provided to address the aforementioned drawbacks.')}

`;

  // Brief Description of Drawings
  if (spec.briefDescriptionOfDrawings && spec.briefDescriptionOfDrawings.length > 0) {
    latex += `
% --- BRIEF DESCRIPTION OF DRAWINGS ---
\\section*{${isUSPTO ? 'BRIEF DESCRIPTION OF THE SEVERAL VIEWS OF THE DRAWINGS' : 'BRIEF DESCRIPTION OF THE ACCOMPANYING DRAWINGS'}}
\\noindent
The accompanying drawings, which are incorporated in and constitute a part of this specification, illustrate preferred embodiments:
\\begin{description}[leftmargin=2cm,style=nextline]
${spec.briefDescriptionOfDrawings.map(d => `  \\item[${escapeLatex(d.figNumber)}] ${escapeLatex(d.description)}`).join('\n')}
\\end{description}
`;
  }

  // Detailed Description of Invention
  latex += `
% --- DETAILED DESCRIPTION OF THE INVENTION ---
\\section*{${isUSPTO ? 'DETAILED DESCRIPTION OF THE PREFERRED EMBODIMENTS' : 'DETAILED DESCRIPTION OF THE INVENTION'}}
\\noindent
The following detailed description refers to the accompanying drawings that form a part hereof. Specific exemplary embodiments are illustrated and described in sufficient detail to enable those skilled in the art to practice the invention.
\\vspace{0.3cm}

`;

  if (spec.detailedDescription?.paragraphs) {
    spec.detailedDescription.paragraphs.forEach(para => {
      latex += `\\noindent
\\textbf{${para.id}} ${escapeLatex(para.text)}

\\vspace{0.3cm}
`;
    });
  }

  // Claims
  latex += `
\\newpage
% ==============================================================================
% CLAIMS
% ==============================================================================
\\section*{${isUSPTO ? 'WHAT IS CLAIMED IS:' : 'WE CLAIM:'}}
\\begin{enumerate}[label=\\bfseries\\arabic*.,leftmargin=1.5cm,itemsep=0.4cm]
`;

  if (spec.claims && spec.claims.length > 0) {
    spec.claims.forEach(c => {
      latex += `  \\item ${escapeLatex(c.text)}\n`;
    });
  } else {
    latex += `  \\item A system comprising a processor and a memory configured to perform operations as described in the specification.\n`;
  }

  latex += `\\end{enumerate}

\\newpage
% ==============================================================================
% ABSTRACT
% ==============================================================================
\\begin{center}
    {\\Large\\bfseries ABSTRACT}\\\\
    \\vspace{0.2cm}
    {\\large\\bfseries ${titleEscaped}}\\\\
\\end{center}
\\vspace{0.4cm}
\\noindent
${escapeLatex(spec.abstract?.text || '')}

\\vspace{0.6cm}
\\noindent
\\textit{Number of Figures accompanying Abstract: ${spec.briefDescriptionOfDrawings?.length || 1}}

\\end{document}
`;

  return latex;
}

function escapeLatex(text: string): string {
  if (!text) return '';
  return text
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'");
}
